#!/usr/bin/env python3
"""Generates src/OneNlp/Tokenizers/Hf/NormalizationData.g.cs: the data of the Unicode normalization forms (UAX #15).

usage: gen_normalization_tables.py <UnicodeData.txt> <DerivedNormalizationProps.txt> <output.cs>

Writes the canonical combining classes, the full canonical and full compatibility decompositions of every code point that has one
(Hangul syllables are algorithmic and left out), and the primary composition pairs (canonical two-character decompositions that are not
excluded from composition).
"""
import re
import sys

ud, props, out = sys.argv[1:4]
version = ""
for line in open(props, encoding="utf-8"):
    m = re.match(r"# DerivedNormalizationProps-([\d.]+)\.txt", line)
    if m:
        version = m.group(1)
        break

ccc = {}
canon = {}   # cp -> list of cps (one level)
compat = {}  # cp -> list of cps (one level, including canonical ones)
range_start = None
for line in open(ud, encoding="utf-8"):
    f = line.rstrip("\n").split(";")
    cp = int(f[0], 16)
    name = f[1]
    if name.endswith(", First>"):
        range_start = cp
        continue
    if name.endswith(", Last>"):
        range_start = None
        continue  # ranges in UnicodeData (CJK, Hangul, private use) carry no decompositions or combining classes
    c = int(f[3])
    if c:
        ccc[cp] = c
    d = f[5]
    if d:
        is_compat = d.startswith("<")
        cps = [int(x, 16) for x in re.sub(r"<[^>]*>\s*", "", d).split()]
        compat[cp] = cps
        if not is_compat:
            canon[cp] = cps

excluded = set()
for line in open(props, encoding="utf-8"):
    line = line.split("#", 1)[0].strip()
    if not line or "Full_Composition_Exclusion" not in line:
        continue
    cps, _ = [p.strip() for p in line.split(";", 1)]
    lo, _, hi = cps.partition("..")
    for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
        excluded.add(cp)


def full(cp, table, memo):
    if cp in memo:
        return memo[cp]
    if cp not in table:
        return [cp]
    result = []
    for x in table[cp]:
        result.extend(full(x, table, memo))
    memo[cp] = result
    return result


full_canon = {cp: full(cp, canon, {}) for cp in canon}
memo = {}
full_compat = {cp: full(cp, compat, memo) for cp in compat}

pairs = sorted((m[0] << 21 | m[1], cp) for cp, m in canon.items() if len(m) == 2 and cp not in excluded)

# Combining class ranges.
ranges = []
for cp in sorted(ccc):
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == ccc[cp]:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, ccc[cp]])


def table(name, mapping, doc):
    keys = sorted(mapping)
    offsets = []
    pool = []
    for k in keys:
        offsets.append(len(pool))
        pool.extend(mapping[k])
    offsets.append(len(pool))
    return keys, offsets, pool


def emit(f, ctype, name, values, doc, per_line=12, fmt=lambda v: f"0x{v:X}"):
    f.write(f"    /// <summary>{doc}</summary>\n")
    f.write(f"    internal static ReadOnlySpan<{ctype}> {name} => new {ctype}[]\n    {{\n")
    for i in range(0, len(values), per_line):
        f.write("        " + ", ".join(fmt(v) for v in values[i:i + per_line]) + ",\n")
    f.write("    };\n\n")


with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write(f"// Generated by tools/gen_normalization_tables.py from the Unicode Character Database {version} (UnicodeData.txt and DerivedNormalizationProps.txt, Unicode License v3). Do not edit.\n")
    f.write("// </auto-generated>\n\n")
    f.write("namespace RecursiveAI.OneNlp.Tokenizers.Hf;\n\n")
    f.write("/// <summary>Data of the Unicode normalization forms.</summary>\n")
    f.write("internal static partial class NormalizationData\n{\n")
    emit(f, "int", "CccStarts", [r[0] for r in ranges], "First code point of each run of one nonzero canonical combining class.")
    emit(f, "int", "CccEnds", [r[1] for r in ranges], "Last code point of each run.")
    emit(f, "byte", "CccValues", [r[2] for r in ranges], "The class of each run.", 24, lambda v: str(v))
    for label, mapping, what in (("Canon", full_canon, "full canonical decomposition"), ("Compat", full_compat, "full compatibility decomposition")):
        keys, offsets, pool = table(label, mapping, what)
        emit(f, "int", f"{label}Keys", keys, f"Code points that have a {what}, ascending.")
        emit(f, "int", f"{label}Offsets", offsets, f"Start of each key's {what} in the pool; one extra entry ends the last.")
        emit(f, "int", f"{label}Pool", pool, f"The {what}s, one after the other.")
    emit(f, "long", "PairKeys", [p[0] for p in pairs], "(first &lt;&lt; 21 | second) of each primary composition pair, ascending.", 8, lambda v: f"0x{v:X}L")
    emit(f, "int", "PairResults", [p[1] for p in pairs], "The composite of each pair.")
    f.write("}\n")
print(f"Unicode {version}: {len(ranges)} ccc runs, {len(full_canon)} canonical, {len(full_compat)} compat, {len(pairs)} pairs")
