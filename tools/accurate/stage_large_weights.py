#!/usr/bin/env python3
"""Stage the base-size model without changing its tensors and generate static head parts.

stage_large_weights.py EXPORT WEIGHTS --repo CHECKOUT --spec CORPUS.json
The six encoder pieces preserve byte order. Additional languages are split into
parts of at most 200 MB uncompressed, leaving room below the feed's 250 MB limit.
The original nine-language package layout remains intact.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

NINE = {'en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'tr', 'zh'}
LIMIT = 200_000_000


def digest(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def manifest(directory, names):
    lines = ['<Project>', '  <!-- Generated by tools/accurate/stage_large_weights.py; weights are not kept in git. -->', '  <ItemGroup>']
    for name, path in names:
        lines.append(f'    <LargeWeight Include="{name}" Size="{path.stat().st_size}" Sha256="{digest(path)}" />')
    lines.extend(['  </ItemGroup>', '</Project>', ''])
    (directory / 'weights.manifest.props').write_text('\n'.join(lines), encoding='utf-8')


def groups(files, limit=LIMIT):
    """Stable sequential grouping, bounded by uncompressed file size, not compression guesses."""
    result = []
    current = []
    size = 0
    for code, path in sorted(files):
        length = path.stat().st_size
        if length > limit:
            raise ValueError(f'Head {code} is too large for one part: {length}')
        if current and size + length > limit:
            result.append(current)
            current, size = [], 0
        current.append((code, path))
        size += length
    if current:
        result.append(current)
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('export', type=Path)
    ap.add_argument('weights', type=Path)
    ap.add_argument('--repo', type=Path, required=True)
    ap.add_argument('--spec', type=Path, required=True)
    a = ap.parse_args()
    languages = sorted(l['code'] for l in json.loads(a.spec.read_text())['languages'])
    a.weights.mkdir(parents=True, exist_ok=True)
    (a.weights / 'heads').mkdir(exist_ok=True)
    package = a.repo / 'src/OneNlp.Models.Multilingual.Large'
    parts = a.repo / 'src/OneNlp.Models.Multilingual.Large.Parts'
    for code in languages:
        shutil.copyfile(a.export / 'heads' / (code + '.onenlp'), a.weights / 'heads' / (code + '.onenlp'))
    shutil.copyfile(a.export / 'heads/zh.onenlp', a.weights / 'zh.onenlp')
    shutil.copyfile(a.export / 'tokenizer.json', a.weights / 'tokenizer.json')
    graph = a.export / 'encoder.onnx'
    length = graph.stat().st_size
    per = (length + 5) // 6
    with graph.open('rb') as f:
        for index, part in enumerate(['Encoder1', 'Encoder2', 'TokenTable1', 'TokenTable2', 'TokenTable3', 'TokenTable4'], 1):
            name = 'encoder.onnx.part' + str(index)
            with (a.weights / name).open('wb') as target:
                remaining = min(per, length - (index - 1) * per)
                while remaining:
                    block = f.read(min(remaining, 1024 * 1024))
                    if not block:
                        raise ValueError('Truncated encoder graph')
                    target.write(block)
                    remaining -= len(block)
            manifest(parts / part, [(name, a.weights / name)])
    manifest(parts / 'Chinese', [('zh.onenlp', a.weights / 'zh.onenlp')])
    manifest(package, [('tokenizer.json', a.weights / 'tokenizer.json')] +
             [('heads/' + code + '.onenlp', a.weights / 'heads' / (code + '.onenlp')) for code in sorted(NINE - {'zh'})])
    all_groups = groups([(code, a.weights / 'heads' / (code + '.onenlp')) for code in languages if code not in NINE])
    dispatch = ['// <auto-generated> by tools/accurate/stage_large_weights.py from the corpus and exported heads. </auto-generated>',
                'namespace RecursiveAI.OneNlp.Models.Multilingual.Large;', '', 'public static partial class MultilingualLargeModel', '{',
                '    /// <summary>The languages this package has heads for (ISO language codes, including three-letter codes).</summary>',
                '    public static IReadOnlyList<string> Languages { get; } = [' + ', '.join('"' + code + '"' for code in languages) + '];', '',
                '    private static Stream OpenHeads(string language) => language switch', '    {', '        "zh" => Chinese.Part.Open(),']
    refs = []
    solution = []
    for index, group in enumerate(all_groups, 1):
        name = 'Heads' + str(index)
        directory = parts / name
        directory.mkdir(exist_ok=True)
        manifest(directory, [('heads/' + code + '.onenlp', path) for code, path in group])
        (directory / ('OneNlp.Models.Multilingual.Large.' + name + '.csproj')).write_text(
            '<Project Sdk="Microsoft.NET.Sdk">\n  <PropertyGroup>\n    <PartName>' + name + '</PartName>\n'
            '    <PartDescription>language-specific heads</PartDescription>\n  </PropertyGroup>\n'
            '  <Import Project="../Part.props" />\n</Project>\n', encoding='utf-8')
        (directory / 'Part.cs').write_text(
            'namespace RecursiveAI.OneNlp.Models.Multilingual.Large.' + name + ';\n\n'
            '/// <summary>Language heads embedded in this part of the base-size accurate-tier model.</summary>\n'
            'public static class Part\n{\n'
            '    /// <summary>Opens the embedded heads for an ISO language code. The caller disposes the returned seekable stream.</summary>\n'
            '    /// <param name="language">The language code assigned to this part.</param>\n'
            '    /// <exception cref="InvalidOperationException">No embedded weights exist for this code.</exception>\n'
            '    public static Stream Open(string language) =>\n'
            '        typeof(Part).Assembly.GetManifestResourceStream("weights/heads/" + language + ".onenlp")\n'
            '        ?? throw new InvalidOperationException("No heads for " + language + "; use the packed model package.");\n}\n', encoding='utf-8')
        (directory / 'PACKAGE.md').write_text(
            '# RecursiveAI.OneNlp.Models.Multilingual.Large.' + name + '\n\nspaCy-class NLP for .NET. '
            'Language heads for the base-size accurate tier. Reference `RecursiveAI.OneNlp.Models.Multilingual.Large`, '
            'which brings this part in automatically. No runtime downloads. Unaffiliated with other projects named OneNLP.\n', encoding='utf-8')
        for code, _ in group:
            dispatch.append(f'        "{code}" => {name}.Part.Open(language),')
        refs.append(f'    <ProjectReference Include="../OneNlp.Models.Multilingual.Large.Parts/{name}/OneNlp.Models.Multilingual.Large.{name}.csproj" />')
        solution.append(f'    <Project Path="src/OneNlp.Models.Multilingual.Large.Parts/{name}/OneNlp.Models.Multilingual.Large.{name}.csproj" />')
    dispatch.extend(['        _ => Resource("heads/" + language + ".onenlp"),', '    };', '}', ''])
    (package / 'MultilingualLargeLanguages.g.cs').write_text('\n'.join(dispatch), encoding='utf-8')
    # This import isolates generated references from the hand-maintained package project.
    (package / 'HeadParts.props').write_text('<Project>\n  <ItemGroup>\n' + '\n'.join(refs) + '\n  </ItemGroup>\n</Project>\n', encoding='utf-8')
    sln = a.repo / 'OneNlp.slnx'
    text = sln.read_text()
    text = '\n'.join(line for line in text.split('\n') if 'OneNlp.Models.Multilingual.Large.Parts/Heads' not in line)
    marker = '    <Project Path="src/OneNlp.Models.Multilingual.Large/OneNlp.Models.Multilingual.Large.csproj" />'
    if marker not in text:
        raise ValueError('Large model project is missing from solution')
    sln.write_text(text.replace(marker, marker + '\n' + '\n'.join(solution)), encoding='utf-8')
    print(f'{len(languages)} languages, {len(all_groups)} additional head parts; encoder {length} bytes sha256 {digest(graph)}')


if __name__ == '__main__':
    main()
