#!/usr/bin/env python3
"""Generates src/OneNlp/Tokenizers/Hf/ScriptData.g.cs from the Unicode Character Database file Scripts.txt.

usage: gen_script_table.py <Scripts.txt> <output.cs>

Code points not listed in Scripts.txt have the script Unknown, as the file's header says.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
version = ""
ranges = []
for line in open(src, encoding="utf-8"):
    if not version:
        m = re.match(r"# Scripts-([\d.]+)\.txt", line)
        if m:
            version = m.group(1)
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    cps, name = [p.strip() for p in line.split(";")]
    lo, _, hi = cps.partition("..")
    lo = int(lo, 16)
    hi = int(hi, 16) if hi else lo
    ranges.append((lo, hi, name))
ranges.sort()

# Merge neighbours of the same script.
merged = []
for lo, hi, name in ranges:
    if merged and merged[-1][2] == name and merged[-1][1] + 1 == lo:
        merged[-1] = (merged[-1][0], hi, name)
    else:
        merged.append((lo, hi, name))

names = ["Unknown"] + sorted({n for _, _, n in merged})
ids = {n: i for i, n in enumerate(names)}

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write(f"// Generated by tools/gen_script_table.py from the Unicode Character Database {version} (Scripts.txt, Unicode License v3). Do not edit.\n")
    f.write("// </auto-generated>\n\n")
    f.write("namespace RecursiveAI.OneNlp.Tokenizers.Hf;\n\n")
    f.write("/// <summary>The Unicode Script property of every code point, as sorted ranges.</summary>\n")
    f.write("internal static partial class ScriptData\n{\n")
    f.write("    /// <summary>Script names; index 0 is <c>Unknown</c>.</summary>\n")
    f.write("    internal static readonly string[] Names =\n    [\n")
    for n in names:
        f.write(f'        "{n}",\n')
    f.write("    ];\n\n")
    f.write("    /// <summary>First code point of each range, ascending.</summary>\n")
    f.write("    internal static ReadOnlySpan<int> Starts => new int[]\n    {\n")
    for i in range(0, len(merged), 12):
        f.write("        " + ", ".join(f"0x{lo:X}" for lo, _, _ in merged[i:i + 12]) + ",\n")
    f.write("    };\n\n")
    f.write("    /// <summary>Last code point of each range.</summary>\n")
    f.write("    internal static ReadOnlySpan<int> Ends => new int[]\n    {\n")
    for i in range(0, len(merged), 12):
        f.write("        " + ", ".join(f"0x{hi:X}" for _, hi, _ in merged[i:i + 12]) + ",\n")
    f.write("    };\n\n")
    f.write("    /// <summary>Index into <see cref=\"Names\"/> of each range.</summary>\n")
    f.write("    internal static ReadOnlySpan<ushort> ScriptIds => new ushort[]\n    {\n")
    for i in range(0, len(merged), 24):
        f.write("        " + ", ".join(str(ids[n]) for _, _, n in merged[i:i + 24]) + ",\n")
    f.write("    };\n}\n")
print(f"{len(merged)} ranges, {len(names)} scripts, Unicode {version}")
