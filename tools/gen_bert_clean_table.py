#!/usr/bin/env python3
"""Generates src/OneNlp/Tokenizers/Hf/BertCleanData.g.cs: the character sets that the reference library's normalizers act on.

usage: gen_bert_clean_table.py <sweep.json.gz> <output.cs>

The sweep file comes from make_sweep.py: for every Unicode scalar value, the output of the reference library's normalizers.
- BertCleanData: code points the BERT text cleaning removes (output of BertNormalizer with only clean_text on is empty). They are control,
  format and private-use characters of the reference library's (older) Unicode data.
- StripAccentsData: code points the StripAccents normalizer removes (marks of the reference library's older Unicode data).
- BertAccentsData: nonspacing marks the uncased BertNormalizer removes (a smaller set: marks assigned from Unicode 9.0 on are kept).
The sets are taken from its behaviour, not computed from our own tables.
"""
import gzip
import json
import sys

sweep, out = sys.argv[1:3]
data = json.load(gzip.open(sweep))


def ranges_of(key):
    dropped = sorted(int(cp) for cp, r in data["changed"][key].items() if r == "")
    ranges = []
    for cp in dropped:
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return dropped, ranges


def emit_class(f, name, doc, ranges):
    f.write(f"/// <summary>{doc}</summary>\n")
    f.write(f"internal static class {name}\n{{\n")
    for part, idx, text in (("Starts", 0, "First code point of each run."), ("Ends", 1, "Last code point of each run.")):
        f.write(f"    /// <summary>{text}</summary>\n")
        f.write(f"    internal static ReadOnlySpan<int> {part} => new int[]\n    {{\n")
        values = [r[idx] for r in ranges]
        for i in range(0, len(values), 12):
            f.write("        " + ", ".join(f"0x{v:X}" for v in values[i:i + 12]) + ",\n")
        f.write("    };\n\n")
    f.write("    /// <summary>Gets whether a code point is in the set.</summary>\n")
    f.write("    /// <param name=\"cp\">The code point.</param>\n")
    f.write("    internal static bool Contains(int cp)\n    {\n")
    f.write("        ReadOnlySpan<int> starts = Starts;\n        ReadOnlySpan<int> ends = Ends;\n")
    f.write("        int lo = 0;\n        int hi = starts.Length - 1;\n        while (lo <= hi)\n        {\n")
    f.write("            int mid = (lo + hi) >>> 1;\n")
    f.write("            if (cp < starts[mid])\n            {\n                hi = mid - 1;\n            }\n")
    f.write("            else if (cp > ends[mid])\n            {\n                lo = mid + 1;\n            }\n")
    f.write("            else\n            {\n                return true;\n            }\n        }\n\n        return false;\n    }\n}\n\n")


def ranges_from(cps):
    ranges = []
    for cp in sorted(cps):
        if ranges and ranges[-1][1] + 1 == cp:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges


clean, clean_ranges = ranges_of("bert_clean")
# What the uncased BertNormalizer removes beyond the cleaning: the nonspacing marks left after decomposition.
bert_accents = sorted(set(int(cp) for cp, r in data["changed"]["bert_uncased"].items() if r == "") - set(clean))
bert_accent_ranges = ranges_from(bert_accents)
strip, strip_ranges = ranges_of("strip_accents")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write(f"// Generated by tools/gen_bert_clean_table.py from the output of {data['oracle']} for every code point. Do not edit.\n")
    f.write("// </auto-generated>\n\n")
    f.write("namespace RecursiveAI.OneNlp.Tokenizers.Hf;\n\n")
    emit_class(f, "BertCleanData", "The code points the BERT text cleaning removes.", clean_ranges)
    emit_class(f, "StripAccentsData", "The code points the accent stripping removes.", strip_ranges)
    emit_class(f, "BertAccentsData", "The nonspacing marks the BERT normalizer removes when it strips accents.", bert_accent_ranges)
print(f"bert accents: {len(bert_accents)}; clean: {len(clean)} code points in {len(clean_ranges)} ranges; strip accents: {len(strip)} in {len(strip_ranges)}")
